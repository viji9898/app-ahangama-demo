export function getPrPromotion(slug) {
  if (!slug) {
    return DEFAULT_PR_PROMOTION;
  }

  const promotion = PR_PROMOTIONS[slug];

  if (!promotion) {
    return DEFAULT_PR_PROMOTION;
  }

  return {
    ...DEFAULT_PR_PROMOTION,
    ...promotion,
    conversion: {
      ...DEFAULT_PR_PROMOTION.conversion,
      ...promotion.conversion,
    },
  };
}
